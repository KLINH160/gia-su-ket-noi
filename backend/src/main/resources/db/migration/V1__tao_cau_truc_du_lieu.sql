CREATE TABLE users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 email VARCHAR(254) NOT NULL,
 password_hash VARCHAR(255) NOT NULL,
 full_name VARCHAR(120) NOT NULL,
 phone VARCHAR(30),
 role VARCHAR(20) NOT NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT ck_user_name CHECK (char_length(btrim(full_name)) BETWEEN 2 AND 120),
 CONSTRAINT ck_user_email CHECK (email = btrim(email) AND char_length(email) > 0),
 CONSTRAINT ck_user_role CHECK (role IN ('PARENT','TUTOR','ADMIN')),
 CONSTRAINT ck_user_status CHECK (status IN ('ACTIVE','LOCKED'))
);
CREATE UNIQUE INDEX uq_users_email_case_insensitive ON users (lower(email));

CREATE TABLE tutor_profiles (
 user_id BIGINT PRIMARY KEY REFERENCES users(id),
 introduction TEXT,
 education VARCHAR(255),
 experience_years INT,
 supports_online BOOLEAN NOT NULL DEFAULT FALSE,
 supports_offline BOOLEAN NOT NULL DEFAULT FALSE,
 teaching_area VARCHAR(120),
 availability_note VARCHAR(500),
 status VARCHAR(30) NOT NULL DEFAULT 'DRAFT',
 version BIGINT NOT NULL DEFAULT 0,
 submitted_at TIMESTAMPTZ,
 updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT ck_profile_status CHECK (status IN ('DRAFT','PENDING_REVIEW','APPROVED','NEEDS_CHANGES')),
 CONSTRAINT ck_profile_experience CHECK (experience_years IS NULL OR experience_years >= 0),
 CONSTRAINT ck_profile_ready CHECK (status NOT IN ('PENDING_REVIEW','APPROVED') OR
   ((supports_online OR supports_offline) AND
    (NOT supports_offline OR (teaching_area IS NOT NULL AND char_length(btrim(teaching_area)) > 0))))
);
CREATE INDEX idx_profile_status ON tutor_profiles(status);

CREATE TABLE subjects (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(100) NOT NULL UNIQUE,
 active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE tutor_offerings (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tutor_id BIGINT NOT NULL REFERENCES tutor_profiles(user_id),
 subject_id BIGINT NOT NULL REFERENCES subjects(id),
 grade_level INT NOT NULL,
 hourly_rate INT NOT NULL,
 CONSTRAINT uq_offering UNIQUE (tutor_id,subject_id,grade_level),
 CONSTRAINT ck_offering_grade CHECK (grade_level BETWEEN 1 AND 12),
 CONSTRAINT ck_offering_rate CHECK (hourly_rate BETWEEN 10000 AND 5000000 AND mod(hourly_rate,1000)=0)
);
CREATE INDEX idx_offering_search ON tutor_offerings(subject_id,grade_level,hourly_rate);

CREATE TABLE profile_reviews (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tutor_id BIGINT NOT NULL REFERENCES tutor_profiles(user_id),
 reviewer_id BIGINT NOT NULL REFERENCES users(id),
 decision VARCHAR(30) NOT NULL,
 reason VARCHAR(1000),
 profile_snapshot JSONB NOT NULL,
 reviewed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT ck_profile_decision CHECK (decision IN ('APPROVED','NEEDS_CHANGES')),
 CONSTRAINT ck_profile_reason CHECK (decision <> 'NEEDS_CHANGES' OR (reason IS NOT NULL AND char_length(btrim(reason))>0))
);
CREATE INDEX idx_profile_review_history ON profile_reviews(tutor_id,reviewed_at);

CREATE TABLE tutoring_requests (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 parent_id BIGINT NOT NULL REFERENCES users(id),
 tutor_id BIGINT NOT NULL REFERENCES tutor_profiles(user_id),
 subject_id BIGINT NOT NULL REFERENCES subjects(id),
 student_name VARCHAR(60) NOT NULL,
 student_name_normalized VARCHAR(60) NOT NULL,
 grade_level INT NOT NULL,
 learning_goal VARCHAR(500) NOT NULL,
 learning_mode VARCHAR(10) NOT NULL,
 learning_area VARCHAR(120),
 desired_schedule VARCHAR(200) NOT NULL,
 proposed_hourly_rate INT NOT NULL,
 desired_start_date DATE NOT NULL,
 note VARCHAR(500),
 status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
 rejection_reason VARCHAR(1000),
 version BIGINT NOT NULL DEFAULT 0,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 resolved_at TIMESTAMPTZ,
 CONSTRAINT ck_request_people CHECK (parent_id <> tutor_id),
 CONSTRAINT ck_request_grade CHECK (grade_level BETWEEN 1 AND 12),
 CONSTRAINT ck_request_mode CHECK (learning_mode IN ('ONLINE','OFFLINE')),
 CONSTRAINT ck_request_area CHECK (learning_mode='ONLINE' OR (learning_area IS NOT NULL AND char_length(btrim(learning_area))>0)),
 CONSTRAINT ck_request_text CHECK (char_length(btrim(student_name))>0 AND char_length(btrim(student_name_normalized))>0 AND char_length(btrim(learning_goal))>0 AND char_length(btrim(desired_schedule))>0),
 CONSTRAINT ck_request_rate CHECK (proposed_hourly_rate BETWEEN 10000 AND 5000000 AND mod(proposed_hourly_rate,1000)=0),
 CONSTRAINT ck_request_status CHECK (status IN ('PENDING','ACCEPTED','REJECTED','CANCELLED')),
 CONSTRAINT ck_request_rejection CHECK (status <> 'REJECTED' OR (rejection_reason IS NOT NULL AND char_length(btrim(rejection_reason))>0)),
 CONSTRAINT ck_request_resolution CHECK ((status='PENDING' AND resolved_at IS NULL) OR (status<>'PENDING' AND resolved_at IS NOT NULL))
);
CREATE UNIQUE INDEX uq_pending_request ON tutoring_requests(parent_id,tutor_id,student_name_normalized,subject_id) WHERE status='PENDING';
CREATE INDEX idx_request_parent ON tutoring_requests(parent_id,status,created_at);
CREATE INDEX idx_request_tutor ON tutoring_requests(tutor_id,status,created_at);

CREATE TABLE tutoring_classes (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 request_id BIGINT NOT NULL UNIQUE REFERENCES tutoring_requests(id),
 status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
 ended_by BIGINT REFERENCES users(id),
 cancellation_reason VARCHAR(1000),
 version BIGINT NOT NULL DEFAULT 0,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 ended_at TIMESTAMPTZ,
 CONSTRAINT ck_class_status CHECK (status IN ('ACTIVE','COMPLETED','CANCELLED')),
 CONSTRAINT ck_class_end CHECK ((status='ACTIVE' AND ended_at IS NULL AND ended_by IS NULL) OR (status<>'ACTIVE' AND ended_at IS NOT NULL AND ended_by IS NOT NULL)),
 CONSTRAINT ck_class_reason CHECK (status<>'CANCELLED' OR (cancellation_reason IS NOT NULL AND char_length(btrim(cancellation_reason))>0))
);

CREATE TABLE reviews (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 class_id BIGINT NOT NULL UNIQUE REFERENCES tutoring_classes(id),
 rating INT NOT NULL,
 comment VARCHAR(1000),
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT ck_review_rating CHECK (rating BETWEEN 1 AND 5)
);

CREATE FUNCTION set_updated_at() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
 NEW.updated_at = clock_timestamp();
 RETURN NEW;
END;
$$;
CREATE TRIGGER trg_users_updated_at BEFORE UPDATE ON users FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER trg_tutor_profiles_updated_at BEFORE UPDATE ON tutor_profiles FOR EACH ROW EXECUTE FUNCTION set_updated_at();
